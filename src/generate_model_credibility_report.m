    passFail(all(TestResults.Status=="PASS"));Equivalence.OverallStatus;"PASS";"PASS"; ...
    "NOT AVAILABLE";"NOT AVAILABLE";passFail(forwardPass);passFail(constrainedPass); ...
    "NOT IMPLEMENTED";"NOT IMPLEMENTED"];
