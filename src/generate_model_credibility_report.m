end

function lines=markdownTable(T)
headers=string(T.Properties.VariableNames); lines=strings(height(T)+2,1);
lines(1)="| "+strjoin(headers," | ")+" |";
lines(2)="|"+strjoin(repmat("---",size(headers)),"|")+"|";
for row=1:height(T)
    values=strings(1,width(T));
    for column=1:width(T)
        value=T{row,column};
        if iscell(value),value=value{1};end
        values(column)=string(value);
        values(column)=replace(values(column),"|","/");
    end
    lines(row+2)="| "+strjoin(values," | ")+" |";
end
lines=lines(:);
end

function value=passFail(condition)
if condition,value="PASS";else,value="FAIL";end
end
