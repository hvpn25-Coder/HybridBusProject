function Credibility = generate_model_credibility_report(databaseFile,options)
%GENERATE_MODEL_CREDIBILITY_REPORT Build the release evidence package.
arguments
    databaseFile (1,1) string = fullfile(hybrid_bus_project_root(), ...
        "data","HybridBus_ComponentDatabase.xlsx")
    options.RunEquivalence (1,1) logical = true
end
root=hybrid_bus_project_root();
resultsFolder=fullfile(root,'results'); documentationFolder=fullfile(root,'documentation');
if ~isfolder(resultsFolder),mkdir(resultsFolder);end
testPath=fullfile(root,'tests'); addpath(testPath);
pathCleanup=onCleanup(@()rmpath(testPath));

TestResults=run_all_hybrid_bus_tests();
Database=load_hybrid_bus_database(databaseFile);
Input=prepare_hybrid_bus_inputs(Database);
DefaultResult=simulate_hybrid_bus_core(Input);
BaselineComparison=compare_powertrain_concepts(DefaultResult,Input);
Sensitivity=run_hybrid_bus_sensitivity_study(databaseFile);
if options.RunEquivalence
    hybridEquivalence=assess_matlab_simulink_equivalence(databaseFile, ...
        struct('PowertrainMode',"Hybrid"));
    bevEquivalence=assess_matlab_simulink_equivalence(databaseFile, ...
        struct('PowertrainMode',"BEV",'InitialBattery1SOE',0.85, ...
        'InitialBattery2SOE',0.85));
    hybridChecks=addvars(hybridEquivalence.SignalChecks, ...
        repmat("Hybrid",height(hybridEquivalence.SignalChecks),1), ...
        'Before',1,'NewVariableNames','Powertrain');
    bevChecks=addvars(bevEquivalence.SignalChecks, ...
        repmat("BEV",height(bevEquivalence.SignalChecks),1), ...
        'Before',1,'NewVariableNames','Powertrain');
    overallStatus=passFail(hybridEquivalence.OverallStatus=="PASS" && ...
        bevEquivalence.OverallStatus=="PASS");
    Equivalence=struct('OverallStatus',overallStatus, ...
        'SignalChecks',[hybridChecks;bevChecks], ...
        'Note',"Independent Hybrid and BEV implementations are compared. "+ ...
        "Equivalence is not measured-vehicle validation.");
else
    Equivalence=struct('OverallStatus',"NOT RUN",'SignalChecks',table);
end

Traceability=requirementsTraceability(TestResults,Equivalence);
GateSummary=credibilityGates(TestResults,Equivalence,Traceability);
Credibility=struct('GeneratedAt',datetime('now'),'DatabaseVersion',Database.Version, ...
    'GateSummary',GateSummary,'Traceability',Traceability,'TestResults',TestResults, ...
    'Equivalence',Equivalence,'BaselineComparison',BaselineComparison, ...
    'Sensitivity',Sensitivity,'DefaultResultSummary',DefaultResult.Summary);

writetable(GateSummary,fullfile(resultsFolder,'Model_Credibility_Summary.csv'));
writetable(Traceability,fullfile(resultsFolder,'Requirements_Traceability_Matrix.csv'));
writetable(BaselineComparison,fullfile(resultsFolder,'Powertrain_Concept_Comparison.csv'));
writetable(Sensitivity.Results,fullfile(resultsFolder,'Sensitivity_Study.csv'));
if ~isempty(Equivalence.SignalChecks)
    writetable(Equivalence.SignalChecks,fullfile(resultsFolder,'MATLAB_Simulink_Equivalence.csv'));
end
save(fullfile(resultsFolder,'HybridBus_Credibility.mat'),'Credibility','-v7.3');
writeCredibilityMarkdown(Credibility,fullfile(documentationFolder,'Model_Credibility_Report.md'));
writeTraceabilityMarkdown(Traceability,fullfile(documentationFolder,'Requirements_Traceability_Matrix.md'));
writeTestReport(Credibility,fullfile(documentationFolder,'Test_Report.md'));
end

