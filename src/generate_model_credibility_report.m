function decision=equivalenceDecision(status)
if status=="PASS"
    decision="Independent Hybrid and BEV implementations agree within declared "+ ...
        "tolerances; do not infer measured-vehicle validation";
else
    decision="Resolve numerical differences before claiming implementation equivalence";
end
end

