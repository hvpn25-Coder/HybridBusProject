function Manifest=download_germany_city_routes(outputFolder)
%DOWNLOAD_GERMANY_CITY_ROUTES Retrieve reproducible German urban circuits.
arguments
    outputFolder (1,1) string = fullfile(hybrid_bus_project_root(), ...
        "documentation","reference_routes","osrm_city")
end
if ~isfolder(outputFolder),mkdir(outputFolder);end

routeID=["DE-MAN-CITY";"DE-STR-CITY";"DE-BER-CITY";"DE-MUC-CITY"; ...
    "DE-HAM-CITY";"DE-FRA-CITY";"DE-CGN-CITY";"DE-DUS-CITY";"DE-LEJ-CITY"];
routeName=["Mannheim Urban Circuit";"Stuttgart Urban Circuit"; ...
    "Berlin Urban Circuit";"Munich Urban Circuit";"Hamburg Urban Circuit"; ...
    "Frankfurt Urban Circuit";"Cologne Urban Circuit"; ...
    "Dusseldorf Urban Circuit";"Leipzig Urban Circuit"];
fileName=["OSRM_Mannheim_City.json";"OSRM_Stuttgart_City.json"; ...
    "OSRM_Berlin_City.json";"OSRM_Munich_City.json";"OSRM_Hamburg_City.json"; ...
    "OSRM_Frankfurt_City.json";"OSRM_Cologne_City.json"; ...
    "OSRM_Dusseldorf_City.json";"OSRM_Leipzig_City.json"];

% Project-defined waypoints are ordered loops through representative city
% districts. OSRM snaps them to the OpenStreetMap driving network.
waypoints={ ...
    [8.4699 49.4790;8.4787 49.4890;8.4665 49.5430;8.5360 49.4550;8.4699 49.4790]; ...
    [9.1829 48.7833;9.2217 48.8042;9.1120 48.7298;9.1680 48.8105;9.1829 48.7833]; ...
    [13.3695 52.5251;13.4132 52.5219;13.3850 52.4730;13.3069 52.5163;13.3695 52.5251]; ...
    [11.5580 48.1402;11.5755 48.1374;11.5510 48.1750;11.6040 48.1270;11.5580 48.1402]; ...
    [10.0067 53.5526;9.9340 53.5528;9.9880 53.6300;10.0000 53.5400;10.0067 53.5526]; ...
    [8.6638 50.1071;8.5706 50.0379;8.6980 50.1120;8.6200 50.1570;8.6638 50.1071]; ...
    [6.9583 50.9430;6.9870 50.9400;7.0000 50.8900;6.9200 50.9500;6.9583 50.9430]; ...
    [6.7940 51.2200;6.7668 51.2895;6.7550 51.2150;6.8700 51.1650;6.7940 51.2200]; ...
    [12.3820 51.3450;12.3730 51.3150;12.3000 51.3200;12.4400 51.3600;12.3820 51.3450]};

distanceKm=zeros(numel(routeID),1); durationHours=zeros(numel(routeID),1);
retrievedUTC=strings(numel(routeID),1);
options=weboptions('Timeout',120,'ContentType','json', ...
    'HeaderFields',{'User-Agent','HybridBusProject/1.5 route research'});
for index=1:numel(routeID)
    points=waypoints{index}; coordinateParts=strings(size(points,1),1);
    for pointIndex=1:size(points,1)
        coordinateParts(pointIndex)=sprintf('%.5f,%.5f',points(pointIndex,1),points(pointIndex,2));
    end
    coordinateText=strjoin(coordinateParts,';');
    queryURL="https://router.project-osrm.org/route/v1/driving/"+coordinateText+ ...
        "?overview=full&geometries=geojson&steps=false&annotations=distance,duration,speed";
    response=webread(queryURL,options);
    assert(string(response.code)=="Ok" && ~isempty(response.routes), ...
        'HybridBus:OSRMCityDownload','OSRM did not return %s.',routeID(index));
    retrievedUTC(index)=string(datetime('now','TimeZone','UTC', ...
        'Format','yyyy-MM-dd''T''HH:mm:ssXXX'));
    payload=struct('RouteID',routeID(index),'RouteName',routeName(index), ...
        'Region',"Germany / urban",'WaypointsLongitudeLatitude',points, ...
        'RetrievedUTC',retrievedUTC(index),'QueryURL',queryURL, ...
        'Attribution',"© OpenStreetMap contributors", ...
        'License',"Open Data Commons Open Database License (ODbL) 1.0", ...
        'UrbanAdaptation',"50 km/h cap; 20 s dwell at nominal 800 m passenger-stop spacing", ...
        'OSRMResponse',response);
    targetFile=fullfile(outputFolder,fileName(index));
    fileID=fopen(targetFile,'w','n','UTF-8');
    assert(fileID>=0,'HybridBus:RouteWrite','Cannot create %s.',targetFile);
    cleanup=onCleanup(@()fclose(fileID));
    fwrite(fileID,jsonencode(payload,'PrettyPrint',true),'char'); clear cleanup
    distanceKm(index)=response.routes(1).distance/1000;
    durationHours(index)=response.routes(1).duration/3600;
end
Manifest=table(routeID,routeName,fileName,distanceKm,durationHours,retrievedUTC);
writetable(Manifest,fullfile(outputFolder,'OSRM_Germany_City_Manifest.csv'));
end
